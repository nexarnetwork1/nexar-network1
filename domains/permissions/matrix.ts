export function permissionsForPlatformRole(role: NbosRole): readonly Permission[] {
  return PLATFORM_ROLE_PERMISSIONS[role];
}

export function permissionsForBusinessMember(
  role: BusinessMemberRole,
): readonly Permission[] {
  return MEMBER_PERMISSIONS[role];
}

export function hasPermission(
  granted: readonly Permission[],
  required: Permission,
): boolean {
  return granted.includes(required);
}

export function resolvePermissions(input: {
  platformRole: NbosRole;
  businessMembership?: BusinessMemberRole | null;
}): Permission[] {
  const set = new Set<Permission>([
    ...permissionsForPlatformRole(input.platformRole),
  ]);
  if (input.businessMembership) {
    for (const p of permissionsForBusinessMember(input.businessMembership)) {
      set.add(p);
    }
  }
  return [...set];
}
